"""숫자를 말로 바꾼다 (docs/chilseong-voice.md 3절). 모델이 어림하지 않게 코드가 한다.

말에서는 어림으로("두 배 가까이", "열에 아홉"), 카드에는 정확한 숫자를 그대로 쓴다.
반올림과 경계의 규칙은 이 파일에만 있고, tests/test_voice.py가 경계값을 고정한다.

배수(ratio, 날값으로 판정한다)
- 1.1 미만        "비슷하게"
- 1.1 이상 1.5 미만 "조금 더"
- n 이상 n+0.5 미만 (n ≥ 2)  "n배 넘게"       예: 2.0~2.4 "두 배 넘게", 4.45 "네 배 넘게"
- n-0.5 이상 n 미만 (n ≥ 2)  "n배 가까이"     예: 1.5~1.9 "두 배 가까이", 2.5~2.9 "세 배 가까이"
  (지시서는 "2.5~3.4 세 배 가까이"라고 적었지만, 3.0 이상은 세 배를 넘으므로 "세 배 넘게"로 한다.
   2.0~2.4 "두 배 넘게"와 같은 규칙이다.)

비율(퍼센트, 정수로 반올림한 뒤 판정한다. .5는 올린다)
- 95 이상 "거의 다", 85~94 "열에 아홉", 56~64 "절반 넘게", 45~55 "절반쯤"
- 그 밖은 10% 단위로 반올림해 "열에 n" (예: 41 → 열에 넷, 65~74 → 열에 일곱, 75~84 → 열에 여덟)
- 5 미만 "열에 하나도 안 되게"
"""

from __future__ import annotations

import math

_KO = ["", "한", "두", "세", "네", "다섯", "여섯", "일곱", "여덟", "아홉", "열"]
_KO_COUNT = ["", "하나", "둘", "셋", "넷", "다섯", "여섯", "일곱", "여덟", "아홉", "열"]


def _half_up(x: float) -> int:
    return int(math.floor(x + 0.5))


def times(ratio: float) -> str:
    """배수를 말로: 1.8 → "두 배 가까이", 4.45 → "네 배 넘게"."""
    r = round(ratio, 6)  # 부동소수의 찌꺼기(2.4999999)를 지운다
    if r < 1.1:
        return "비슷하게"
    if r < 1.5:
        return "조금 더"
    n = int(math.floor(r))
    if r - n < 0.5:
        return f"{_num(n)} 배 넘게"
    return f"{_num(n + 1)} 배 가까이"


def _num(n: int) -> str:
    return _KO[n] if n < len(_KO) else str(n)


def share(pct: float) -> str:
    """비율(%)을 말로: 87 → "열에 아홉", 41 → "열에 넷", 50 → "절반쯤"."""
    p = _half_up(pct)
    if p >= 95:
        return "거의 다"
    if 85 <= p <= 94:
        return "열에 아홉"
    if 56 <= p <= 64:
        return "절반 넘게"
    if 45 <= p <= 55:
        return "절반쯤"
    if p < 5:
        return "열에 하나도 안 되게"
    tens = max(1, min(9, _half_up(p / 10)))
    return f"열에 {_KO_COUNT[tens]}"


def count(n: int) -> str:
    """개수를 관형어로: 2 → "두", 3 → "세"."""
    return _num(n)


# ---------- 시간대, 장소, 동반, 음식 동반의 입말 ----------
# 기록(2024 국민건강영양조사 집계 파일)의 값 → 말. 카드에는 consumer.py의 이름을 그대로 쓴다.
SPOKEN_WHEN: dict[str, dict[str, str]] = {
    "시간대": {"1 아침(05~09시)": "아침에", "2 오전(09~11시)": "오전에", "3 점심(11~14시)": "점심에",
              "4 오후(14~17시)": "오후에", "5 저녁(17~21시)": "저녁에", "6 밤(21~05시)": "밤에"},
    "장소": {"가정": "집에서", "직장·학교": "일터나 학교에서", "음식점": "음식점에서", "기타": "밖에서"},
    "동반": {"혼자": "혼자", "가족과": "가족과", "가족이 아닌 사람과": "다른 사람들과"},
    "음식 동반": {"음식과 함께": "밥 먹을 때", "음료만": "음료만 마실 때"},
}


def when_word(axis: str, raw: str) -> str | None:
    """기록의 값(예: "5 저녁(17~21시)")을 입말("저녁에")로. 모르는 값이면 None."""
    return SPOKEN_WHEN.get(axis, {}).get(raw)
